import React, { useState, useEffect } from 'react';
import api from '../../services/api';
import toast from 'react-hot-toast';

const SCORE_COLOR = s => s >= 85 ? '#16a34a' : s >= 65 ? '#d97706' : '#2563eb';

const STATUS_MAP = {
  pending: { c: 'badge-warning', t: '🟡 Pending' },
  contact_requested: { c: 'badge-info', t: '📬 Contact Sent' },
  contact_accepted: { c: 'badge-primary', t: '💬 Chatting' },
  contact_rejected: { c: 'badge-danger', t: '❌ Rejected' },
  verifying: { c: 'badge-info', t: '🔎 Verifying' },
  handover_scheduled: { c: 'badge-primary', t: '📅 Handover Set' },
  returned: { c: 'badge-success', t: '✅ Returned' },
  false_match: { c: 'badge-danger', t: '❌ False Match' },
  closed: { c: 'badge-gray', t: '🔒 Closed' },
};

export default function AdminMatches() {
  const [matches, setMatches] = useState([]);
  const [loading, setLoading] = useState(true);
  const [filter, setFilter] = useState('');

  useEffect(() => {
    api.get('/admin/matches')
      .then(r => setMatches(r.data.matches || []))
      .catch(() => toast.error('Failed to load matches'))
      .finally(() => setLoading(false));
  }, []);

  const filtered = filter ? matches.filter(m => m.status === filter) : matches;

  return (
    <div>
      <div className="page-header" style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start' }}>
        <div>
          <h1 className="page-title">🎯 All Matches</h1>
          <p className="page-subtitle">{matches.length} total matches generated by the smart matching engine</p>
        </div>
      </div>

      {/* Stats row */}
      <div style={{ display: 'flex', gap: '1rem', marginBottom: '1.5rem', flexWrap: 'wrap' }}>
        {[
          ['All', '', matches.length],
          ['Returned', 'returned', matches.filter(m => m.status === 'returned').length],
          ['Chatting', 'contact_accepted', matches.filter(m => m.status === 'contact_accepted').length],
          ['Pending', 'pending', matches.filter(m => m.status === 'pending').length],
          ['Rejected', 'contact_rejected', matches.filter(m => m.status === 'contact_rejected').length],
        ].map(([label, val, count]) => (
          <div key={label} onClick={() => setFilter(val)}
            style={{ background: filter === val ? '#2563eb' : 'white', color: filter === val ? 'white' : '#374151', border: `1px solid ${filter === val ? '#2563eb' : '#e5e7eb'}`, borderRadius: 8, padding: '0.625rem 1rem', cursor: 'pointer', fontSize: '0.875rem', fontWeight: 600 }}>
            {label} <span style={{ background: filter === val ? 'rgba(255,255,255,0.2)' : '#f3f4f6', borderRadius: 99, padding: '0.05rem 0.4rem', marginLeft: '0.3rem', fontSize: '0.75rem' }}>{count}</span>
          </div>
        ))}
      </div>

      {loading ? <div className="loading-overlay"><div className="spinner spinner-lg" /></div> : filtered.length === 0 ? (
        <div className="empty-state">
          <div className="empty-state-icon">🎯</div>
          <h3>No Matches</h3>
          <p>No matches found with the selected filter.</p>
        </div>
      ) : (
        <div className="table-wrapper">
          <table>
            <thead>
              <tr>
                <th>Match Score</th>
                <th>Lost Item</th>
                <th>Owner</th>
                <th>Found Item</th>
                <th>Finder</th>
                <th>Status</th>
                <th>Date</th>
              </tr>
            </thead>
            <tbody>
              {filtered.map(m => (
                <tr key={m.id}>
                  <td>
                    <div style={{ display: 'flex', alignItems: 'center', gap: '0.5rem' }}>
                      <div style={{ width: 48, height: 48, borderRadius: '50%', background: `${SCORE_COLOR(m.match_score)}20`, border: `2px solid ${SCORE_COLOR(m.match_score)}`, display: 'flex', alignItems: 'center', justifyContent: 'center', fontWeight: 800, color: SCORE_COLOR(m.match_score), fontSize: '0.85rem' }}>
                        {m.match_score}%
                      </div>
                    </div>
                  </td>
                  <td>
                    <div style={{ fontWeight: 600, fontSize: '0.9rem' }}>{m.lost_name}</div>
                    <div style={{ fontFamily: 'monospace', fontSize: '0.72rem', color: '#9ca3af' }}>{m.lost_id}</div>
                  </td>
                  <td style={{ fontSize: '0.875rem', fontWeight: 500 }}>{m.owner_name}</td>
                  <td>
                    <div style={{ fontWeight: 600, fontSize: '0.9rem' }}>{m.found_name}</div>
                    <div style={{ fontFamily: 'monospace', fontSize: '0.72rem', color: '#9ca3af' }}>{m.found_id}</div>
                  </td>
                  <td style={{ fontSize: '0.875rem', fontWeight: 500 }}>{m.finder_name}</td>
                  <td>
                    <span className={`badge ${STATUS_MAP[m.status]?.c || 'badge-gray'}`} style={{ fontSize: '0.72rem' }}>
                      {STATUS_MAP[m.status]?.t || m.status}
                    </span>
                  </td>
                  <td style={{ fontSize: '0.8rem', color: '#9ca3af' }}>
                    {new Date(m.created_at).toLocaleDateString('en-IN')}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
    </div>
  );
}
